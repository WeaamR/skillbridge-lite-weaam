import { createFileRoute, Link, notFound } from "@tanstack/react-router";
import { useEffect, useRef, useState } from "react";
import { Button } from "@/components/ui/button";
import { analyzeFit, type FitAnalysis } from "@/lib/fit-analysis.functions";
import {
  OPPORTUNITIES,
  demoPreview,
  hasEnoughData,
  useProfile,
} from "@/lib/skillbridge";

export const Route = createFileRoute("/opportunities/$id/analysis")({
  loader: ({ params }) => {
    const o = OPPORTUNITIES.find((x) => x.id === params.id);
    if (!o) throw notFound();
    return o;
  },
  head: ({ loaderData }) => ({
    meta: [
      { title: `Fit Analysis: ${loaderData?.title ?? "Opportunity"} — SkillBridge Lite` },
      { name: "description", content: "See relevant skills, potential gaps, and next steps." },
      { property: "og:title", content: "AI Fit Analysis — SkillBridge Lite" },
      { property: "og:description", content: "See relevant skills, potential gaps, and next steps." },
    ],
  }),
  component: Analysis,
});

type State =
  | { kind: "idle" }
  | { kind: "analyzing" }
  | { kind: "success"; result: FitAnalysis }
  | { kind: "insufficient" }
  | { kind: "unavailable"; message: string }
  | { kind: "invalid"; message: string }
  | { kind: "error"; message: string };

function Analysis() {
  const o = Route.useLoaderData();
  const { profile, isSample } = useProfile();
  const [state, setState] = useState<State>({ kind: "idle" });
  const [showDemo, setShowDemo] = useState(false);
  const runId = useRef(0);

  // A profile change invalidates any previous result.
  useEffect(() => {
    runId.current += 1;
    setState({ kind: "idle" });
    setShowDemo(false);
  }, [profile]);

  const analyze = async () => {
    if (!hasEnoughData(profile)) {
      setState({ kind: "insufficient" });
      return;
    }
    const id = ++runId.current;
    setState({ kind: "analyzing" });
    try {
      const r = await analyzeFit({ data: { profile, opportunity: o } });
      if (runId.current !== id) return;
      if (r.ok) setState({ kind: "success", result: r.result });
      else if (r.code === "unavailable" || r.code === "credits")
        setState({ kind: "unavailable", message: r.message });
      else if (r.code === "invalid_output") setState({ kind: "invalid", message: r.message });
      else setState({ kind: "error", message: r.message });
    } catch {
      if (runId.current === id)
        setState({ kind: "error", message: "The analysis could not be completed. Please check your connection and try again." });
    }
  };

  const demo = demoPreview(profile, o);

  return (
    <section className="mx-auto max-w-3xl px-5 py-12">
      <Link to="/opportunities/$id" params={{ id: o.id }} className="text-sm text-muted-foreground hover:text-foreground">
        ← Back to {o.title}
      </Link>
      <h1 className="mt-6 font-display text-3xl font-semibold tracking-tight">AI Fit Analysis</h1>
      <p className="mt-2 text-muted-foreground">
        {o.title} at {o.company} · Profile: {profile.name || "Unnamed"}
        {isSample && " (sample profile)"}
      </p>

      <div className="mt-8 rounded-xl border border-border bg-card p-6 shadow-sm">
        {state.kind === "idle" && (
          <div>
            <h2 className="font-semibold">Ready to analyze your fit</h2>
            <p className="mt-2 text-sm text-muted-foreground">
              We will compare your saved profile against this opportunity and show your relevant
              skills, potential gaps, and recommended next steps.
            </p>
            <Button className="mt-4" onClick={analyze}>Analyze My Fit</Button>
          </div>
        )}

        {state.kind === "analyzing" && (
          <div className="flex items-center gap-3" role="status" aria-live="polite">
            <span
              className="h-5 w-5 animate-spin rounded-full border-2 border-primary border-t-transparent"
              aria-hidden="true"
            />
            <p className="text-muted-foreground">Analyzing your profile against this opportunity…</p>
          </div>
        )}

        {state.kind === "success" && (
          <div>
            <h2 className="font-semibold">Your fit analysis</h2>
            <p className="mt-1 text-xs text-muted-foreground">
              Generated by AI from your saved profile and this opportunity. It is guidance only and does not predict hiring outcomes.
            </p>
            <div className="mt-6 grid gap-4 md:grid-cols-3">
              <RichSection title="Relevant Skills" empty="No clearly evidenced matching skills were found."
                items={state.result.relevantSkills.map((x) => ({ head: x.item, lines: [["Evidence", x.evidence], ["Relevance", x.relevance]] }))} />
              <RichSection title="Potential Gaps" empty="No gaps were identified."
                items={state.result.potentialGaps.map((x) => ({ head: x.requirement, lines: [["Why", x.reason]] }))} />
              <RichSection title="Recommended Next Steps" empty="No specific next steps were suggested."
                items={state.result.recommendedNextSteps.map((x) => ({ head: x.action, lines: [["Why", x.reason]] }))} />
            </div>
          </div>
        )}

        {state.kind === "insufficient" && (
          <Notice title="Not enough profile information">
            Add your skills and at least one project or experience entry to analyze your fit.
            <Button asChild className="mt-4 block w-fit"><Link to="/profile">Complete My Profile</Link></Button>
          </Notice>
        )}

        {state.kind === "unavailable" && (
          <Notice title="Real AI analysis is currently unavailable">
            {state.message} A real AI-generated analysis could not be performed, and no analysis
            result was produced.
            {!showDemo && (
              <span className="mt-4 flex flex-wrap gap-2">
              <Button variant="outline" onClick={analyze}>Try Again</Button>
              <Button variant="outline" onClick={() => setShowDemo(true)}>
                Show demonstration example
              </Button>
              </span>
            )}
          </Notice>
        )}

        {state.kind === "invalid" && (
          <Notice title="The AI response could not be used">
            {state.message} No result is shown because it did not pass validation.
            <Button variant="outline" className="mt-4 block w-fit" onClick={analyze}>Try Again</Button>
          </Notice>
        )}

        {state.kind === "error" && (
          <Notice title="Something went wrong">
            {state.message}
            <Button variant="outline" className="mt-4 block w-fit" onClick={analyze}>Try Again</Button>
          </Notice>
        )}
      </div>

      {state.kind === "unavailable" && showDemo && (
        <div className="mt-6 rounded-xl border-2 border-dashed border-primary/40 p-6">
          <p className="inline-block rounded-full bg-primary/10 px-3 py-1 text-xs font-semibold uppercase tracking-wide text-primary">
            Demonstration example — not a real AI analysis
          </p>
          <p className="mt-3 text-sm text-muted-foreground">
            This preview only matches required skill names against words in your profile.
          </p>
          <div className="mt-6 grid gap-4 md:grid-cols-3">
            <Section title="Relevant Skills" items={demo.relevant} empty="No matching skills found." />
            <Section title="Potential Gaps" items={demo.gaps} empty="No gaps found." />
            <Section title="Recommended Next Steps" items={demo.steps} empty="Keep your profile up to date." />
          </div>
        </div>
      )}
    </section>
  );
}

function Notice({ title, children }: { title: string; children: React.ReactNode }) {
  return (
    <div>
      <h2 className="font-semibold">{title}</h2>
      <div className="mt-2 text-sm text-muted-foreground">{children}</div>
    </div>
  );
}

function Section({ title, items, empty }: { title: string; items: string[]; empty: string }) {
  return (
    <div className="rounded-lg border border-border bg-card p-4">
      <h3 className="font-semibold">{title}</h3>
      {items.length ? (
        <ul className="mt-2 list-disc space-y-1 pl-5 text-sm text-muted-foreground">
          {items.map((i) => <li key={i}>{i}</li>)}
        </ul>
      ) : (
        <p className="mt-2 text-sm text-muted-foreground">{empty}</p>
      )}
    </div>
  );
}

function RichSection({ title, items, empty }: { title: string; items: { head: string; lines: [string, string][] }[]; empty: string }) {
  return (
    <div className="rounded-lg border border-border bg-card p-4">
      <h3 className="font-semibold">{title}</h3>
      {items.length ? (
        <ul className="mt-3 space-y-3 text-sm">
          {items.map((i, n) => (
            <li key={n}>
              <p className="font-medium">{i.head}</p>
              {i.lines.map(([k, v]) => (
                <p key={k} className="mt-1 text-muted-foreground"><span className="font-medium text-foreground/80">{k}:</span> {v}</p>
              ))}
            </li>
          ))}
        </ul>
      ) : (
        <p className="mt-2 text-sm text-muted-foreground">{empty}</p>
      )}
    </div>
  );
}
